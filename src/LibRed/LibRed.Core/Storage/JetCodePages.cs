    /// <summary>The code page ACE writes for a database in <paramref name="collation"/>, or null when it has
    /// not been measured for that order's language.</summary>
    public static int? For(Collation collation) =>
        ByLangId.TryGetValue(collation.Lcid & 0xFFFF, out int codePage) ? codePage : null;

    private static FrozenDictionary<int, int> Build((int CodePage, int[] LangIds)[] groups) =>
        groups.SelectMany(g => g.LangIds.Select(langId => (langId, g.CodePage)))
            .ToFrozenDictionary(e => e.langId, e => e.CodePage);
